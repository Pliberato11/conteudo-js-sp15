// Exercício 2: Subtração de valores informados pelo usuário
alert("Subtração de Valores Informados");

let valor1 = parseFloat(prompt("Informe o primeiro valor: "));

let valor2 = parseFloat(prompt("Informe o segundo valor: "));

let resultadoSubtracao = valor1 - valor2;

alert("O resultado da subtração dos valores informados é: " + resultadoSubtracao);