// Exercício 3: Multiplicação de valores informados pelo usuário
alert("Multiplicação de Valores Informados");

let valor1 = parseFloat(prompt("Informe o primeiro valor: "));

let valor2 = parseFloat(prompt("Informe o segundo valor: "));

let resultadoMultiplicacao = valor1 * valor2;

alert("O resultado da multiplicação dos valores informados é: " + resultadoMultiplicacao);