// Exercício 6: Calculando área de retângulo.
alert("Área de Retângulo");

let alturaRetangulo = parseFloat(prompt("Informe a altura do retângulo em centímetros: "));

let larguraRetangulo = parseFloat(prompt("Informe a largura do retângulo em centímetros: "));

let areaRetangulo = alturaRetangulo * larguraRetangulo;

alert("A área total do retângulo de altura " + alturaRetangulo + " cm e largura " + larguraRetangulo + " cm é: " + areaRetangulo + " cm²");